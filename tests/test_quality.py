import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile
import unittest


ROOT = Path(__file__).resolve().parents[1]


class QualityTests(unittest.TestCase):
    def setUp(self):
        fixtures = ROOT / ".cache/test-fixtures"
        fixtures.mkdir(parents=True, exist_ok=True)
        self.root = Path(tempfile.mkdtemp(prefix="quality files ", dir=fixtures))
        (self.root / "tools/quality").mkdir(parents=True)
        shutil.copyfile(ROOT / "tools/quality/run.py", self.root / "tools/quality/run.py")
        shutil.copyfile(ROOT / "Makefile", self.root / "Makefile")
        for name in ["mailbox.go", "herdr.go", "main.go", "control.go", "deleted.go"]:
            self.write("host/internal/bridge/" + name, "package bridge\n")
        self.write("host/cmd/pissbox-bridge/main.go", "package main\n")
        self.write("pi-agent/extensions/bridge.js", "export default () => {};\n")
        self.write(".gitignore", ".cache/\nignored.go\n")
        self.git("init", "-q")
        self.git("add", ".")
        self.commit("base")
        self.base = self.git("rev-parse", "HEAD").stdout.strip()
        self.env = {key: value for key, value in os.environ.items()
                    if not key.startswith("QUALITY_")
                    and key not in ("PISSBOX_BRIDGE_TEST_FIXTURE_DIR", "PISSBOX_LAUNCHER_TEST_RESOURCE_DIR")}
        self.env["PYTHONDONTWRITEBYTECODE"] = "1"

    def write(self, name, text):
        path = self.root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        return path

    def git(self, *args):
        return subprocess.run(["git", *args], cwd=self.root, check=True, capture_output=True, text=True)

    def commit(self, message):
        self.git("-c", "user.name=Quality Test", "-c", "user.email=quality@example.invalid", "commit", "-qm", message)

    def quality(self, *args, **env):
        return subprocess.run(
            ["python3", "tools/quality/run.py", *args], cwd=self.root,
            env={**self.env, **env}, capture_output=True, text=True, timeout=10,
        )

    def selection(self, *args, **env):
        result = self.quality(*args, "--list", **env)
        self.assertEqual(result.returncode, 0, result.stderr)
        return json.loads(result.stdout)

    def test_requires_scope_and_help_does_not_require_tools(self):
        result = self.quality("mutation-go")
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("Choose BASE=", result.stderr)
        help_result = self.quality("--help")
        self.assertEqual(help_result.returncode, 0, help_result.stderr)
        self.assertIn("--list", help_result.stdout)

    def test_explicit_files_override_base_and_preserve_spaces_and_metacharacters(self):
        self.write("host/internal/bridge/my [worker].go", "package bridge\n")
        files = "'host/internal/bridge/my [worker].go' pi-agent/extensions/bridge.js"
        self.assertEqual(self.selection("mutation-go", QUALITY_FILES=files, QUALITY_BASE="bad-ref"), ["host/internal/bridge/my [worker].go"])
        self.assertEqual(self.selection("mutation-js", QUALITY_FILES=files), ["pi-agent/extensions/bridge.js"])

    def test_base_includes_feature_commits_staged_unstaged_untracked_and_renamed_destinations(self):
        self.write("host/internal/bridge/mailbox.go", "package bridge\n// committed\n")
        self.git("add", "host/internal/bridge/mailbox.go")
        self.commit("feature")
        self.write("host/internal/bridge/herdr.go", "package bridge\n// staged\n")
        self.git("add", "host/internal/bridge/herdr.go")
        self.write("host/cmd/pissbox-bridge/main.go", "package main\n// unstaged\n")
        self.git("mv", "host/internal/bridge/control.go", "host/internal/bridge/control renamed.go")
        self.git("rm", "host/internal/bridge/deleted.go")
        self.write("host/internal/bridge/new [worker].go", "package bridge\n")
        self.write("host/internal/bridge/main_test.go", "package bridge\n")
        self.write("host/internal/bridge/generated.go", "// Code generated by test. DO NOT EDIT.\npackage bridge\n")
        self.write("host/vendor/library.go", "package library\n")
        self.write("host/internal/bridge/testdata/example.go", "package example\n")
        self.write("host/internal/bridge/ignored.go", "package bridge\n")
        self.assertEqual(self.selection("mutation-go", "--base", self.base), [
            "host/cmd/pissbox-bridge/main.go", "host/internal/bridge/control renamed.go",
            "host/internal/bridge/herdr.go", "host/internal/bridge/mailbox.go",
            "host/internal/bridge/new [worker].go",
        ])

    def test_base_uses_merge_base_not_the_tip_of_the_other_branch(self):
        self.git("checkout", "-qb", "other")
        self.write("host/cmd/pissbox-bridge/main.go", "package main\n// other branch only\n")
        self.git("add", "host/cmd/pissbox-bridge/main.go")
        self.commit("other branch")
        self.git("checkout", "-qb", "feature", self.base)
        self.write("host/internal/bridge/mailbox.go", "package bridge\n// feature only\n")
        self.assertEqual(self.selection("mutation-go", "--base", "other"), ["host/internal/bridge/mailbox.go"])

    def test_test_only_changes_are_a_successful_noop_without_installed_tools(self):
        self.write("host/internal/bridge/mailbox_test.go", "package bridge\n")
        result = self.quality("mutation-go", "--base", self.base)
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("No matching go source changes", result.stdout)

    def test_invalid_scopes_fail_without_falling_back_to_all_files(self):
        for args in [
            ["--base", "no-such-ref"], ["host/internal/bridge/missing.go"], ["Makefile"],
            ["--all", "host/cmd/pissbox-bridge/main.go"], ["--all", "--base", self.base],
        ]:
            with self.subTest(args=args):
                result = self.quality("mutation-go", *args)
                self.assertNotEqual(result.returncode, 0)
                self.assertNotIn("Selected source files", result.stdout)

    def test_all_is_explicit_for_mutation_but_default_for_metrics(self):
        expected = sorted(["host/cmd/pissbox-bridge/main.go", *(
            "host/internal/bridge/" + name for name in ["mailbox.go", "herdr.go", "main.go", "control.go", "deleted.go"]
        )])
        self.assertEqual(self.selection("mutation-go", "--all"), expected)
        self.assertEqual(self.selection("crap-go"), expected)

    def test_go_adapter_excludes_exact_complement_and_preserves_failure_status(self):
        stub_bin = self.root / "stubs"
        stub_bin.mkdir()
        go = self.write("stubs/go", "#!/bin/sh\nprintf 'test-os\\ntest-arch\\n'\n")
        go.chmod(0o755)
        tool = self.write(".cache/quality-tools/bin/test-os-test-arch/gremlins", """#!/usr/bin/env python3
import json, os, sys
from pathlib import Path
Path(os.environ['CALL_LOG']).write_text(json.dumps({
    'args': sys.argv[1:], 'cwd': os.getcwd(), 'flags': os.environ['GOFLAGS'],
    'fixtures': os.environ['PISSBOX_BRIDGE_TEST_FIXTURE_DIR'],
    'resources': os.environ['PISSBOX_LAUNCHER_TEST_RESOURCE_DIR'],
}))
sys.exit(int(os.environ.get('TOOL_STATUS', '0')))
""")
        tool.chmod(0o755)
        selected = "host/internal/bridge/my [worker].go"
        self.write(selected, "package bridge\n")
        self.write("host/internal/bridge/generated.go", "// Code generated by test. DO NOT EDIT.\npackage bridge\n")
        log = self.root / "calls.json"
        result = self.quality("mutation-go", selected, "--dry-run", PATH=str(stub_bin) + os.pathsep + self.env["PATH"], CALL_LOG=str(log), TOOL_STATUS="9")
        self.assertEqual(result.returncode, 9, result.stderr)
        call = json.loads(log.read_text())
        self.assertIn("--integration", call["args"])
        self.assertIn("--dry-run", call["args"])
        self.assertIn("--workers=1", call["args"])
        self.assertIn("-count=1", call["flags"])
        self.assertEqual(call["cwd"], str(self.root / "host"))
        self.assertEqual(call["fixtures"], str(self.root / ".cache/test-fixtures"))
        self.assertEqual(call["resources"], str(self.root))
        patterns = [arg.split("=", 1)[1] for arg in call["args"] if arg.startswith("--exclude-files=")]
        self.assertFalse(any(re.search(pattern, "internal/bridge/my [worker].go") for pattern in patterns))
        self.assertTrue(any(re.search(pattern, "internal/bridge/main.go") for pattern in patterns))
        self.assertTrue(any(re.search(pattern, "cmd/pissbox-bridge/main.go") for pattern in patterns))
        self.assertTrue(any(re.search(pattern, "internal/bridge/generated.go") for pattern in patterns))
        self.assertFalse(any(re.search(pattern, "internal/bridge/not-main.go") for pattern in patterns))
        self.assertFalse(any(re.search(pattern, "other/internal/bridge/main.go") for pattern in patterns))
        # Explicit short fixture roots must survive the copied-module adapter.
        fixtures = str(self.root / ".cache/test-fixtures/override")
        result = self.quality("mutation-go", selected, "--dry-run",
                              PATH=str(stub_bin) + os.pathsep + self.env["PATH"],
                              CALL_LOG=str(log), PISSBOX_BRIDGE_TEST_FIXTURE_DIR=fixtures,
                              PISSBOX_LAUNCHER_TEST_RESOURCE_DIR=str(ROOT))
        self.assertEqual(result.returncode, 0, result.stderr)
        call = json.loads(log.read_text())
        self.assertEqual(call["fixtures"], fixtures)
        self.assertEqual(call["resources"], str(ROOT))

    @unittest.skipUnless(
        shutil.which("node") and (ROOT / ".cache/quality-tools/js/node_modules/@stryker-mutator/core/package.json").is_file(),
        "run make tools to enable the real Stryker literal-path check",
    )
    def test_js_runners_discover_colocated_tests_and_stryker_mutates_only_the_literal_path(self):
        shutil.copyfile(ROOT / "tools/quality/javascript.mjs", self.root / "tools/quality/javascript.mjs")
        (self.root / ".cache/quality-tools").mkdir(parents=True)
        (self.root / ".cache/quality-tools/js").symlink_to(ROOT / ".cache/quality-tools/js", target_is_directory=True)
        selected = "pi-agent/extensions/my [worker].js"
        self.write(selected, "export default function value(n) { return n > 0; }\n")
        self.write("pi-agent/auth.json", "not-a-secret test sentinel\n")
        self.write("host/go.mod", "module fixture\n")
        self.write("host/go.sum", "")
        self.write("tests/pi-installation.mjs", "export const helper = true;\n")
        self.write("tests/helper.test.mjs", '''import assert from "node:assert/strict";
import { appendFileSync } from "node:fs";
import { helper } from "./pi-installation.mjs";
assert.equal(helper, true);
appendFileSync(process.env.DISCOVERY_LOG, "helper\\n");
''')
        self.write("pi-agent/extensions/new [suite].test.mjs", '''import assert from "node:assert/strict";
import { appendFileSync } from "node:fs";
import value from "./my [worker].js";
import { helper } from "../../tests/pi-installation.mjs";
assert.equal(value(1), true);
assert.equal(helper, true);
appendFileSync(process.env.DISCOVERY_LOG, "root\\n");
''')
        self.write("pi-agent/extensions/lib/new-nested.test.mjs", '''import assert from "node:assert/strict";
import { appendFileSync, existsSync } from "node:fs";
for (const name of ["cmd/pissbox-bridge/main.go", "internal/bridge/mailbox.go", "go.mod", "go.sum"]) {
    assert.ok(existsSync(new URL("../../../host/" + name, import.meta.url)), name);
}
if (process.env.PISSBOX_BRIDGE_TEST_FIXTURE_DIR) {
    assert.ok(process.env.PISSBOX_BRIDGE_TEST_FIXTURE_DIR.endsWith("/.cache/test-fixtures"));
    assert.ok(!process.env.PISSBOX_BRIDGE_TEST_FIXTURE_DIR.includes("/sandboxes/"));
}
appendFileSync(process.env.DISCOVERY_LOG, "nested\\n");
''')
        self.write("pi-agent/extensions/not-a-test.mjs", 'throw new Error("must not discover helpers");\n')
        log = self.root / "discovery.log"
        for runner in ["make", "coverage", "mutation"]:
            with self.subTest(runner=runner):
                log.write_text("")
                if runner == "make":
                    result = subprocess.run(
                        ["make", "test-js"], cwd=self.root, env={**self.env, "DISCOVERY_LOG": str(log)},
                        capture_output=True, text=True, timeout=10,
                    )
                elif runner == "coverage":
                    result = self.quality("coverage-js", DISCOVERY_LOG=str(log))
                else:
                    result = self.quality("mutation-js", "--dry-run", selected, DISCOVERY_LOG=str(log))
                self.assertEqual(result.returncode, 0, result.stderr + result.stdout)
                self.assertEqual(sorted(log.read_text().splitlines()), ["helper", "nested", "root"],
                                 "discover every suite once, without an explicit filename list")
        self.assertIn("Instrumented 1 source file(s)", result.stdout)
        self.assertNotIn("did not result in any files", result.stdout)
        sandboxes = self.root / ".cache/mutation/js/sandboxes"
        unselected = list(sandboxes.rglob("bridge.js"))
        self.assertTrue(unselected)
        self.assertFalse(list(sandboxes.rglob("auth.json")))

    def test_make_passes_files_as_data_not_shell_commands(self):
        name = "host/internal/bridge/my file; touch SHOULD_NOT_EXIST.go"
        self.write(name, "package main\n")
        result = subprocess.run(
            ["make", "mutation-go", "PYTHON=python3", f"FILES='{name}'"], cwd=self.root,
            env=self.env, capture_output=True, text=True, timeout=10,
        )
        self.assertNotEqual(result.returncode, 0)
        self.assertIn(name, result.stdout)
        self.assertIn("run make tools first", result.stderr)
        self.assertFalse((self.root / "SHOULD_NOT_EXIST.go").exists())


if __name__ == "__main__":
    unittest.main()
